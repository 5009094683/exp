export function getAgent(slug: string): Agent | undefined {
  return agents.find((agent) => agent.slug === slug);
}

export const MODEL_PROFILES: Record<ModelProfile, { label: string; description: string }> = {
  fast: { label: "Fast", description: "Low latency for classification and routing." },
  balanced: { label: "Balanced", description: "General-purpose reasoning and drafting." },
  reasoning: { label: "Reasoning", description: "Multi-step analysis for high-stakes work." },
};

/** Workspace totals derived from the agents, so every view shows consistent numbers. */
export const fleet = {
  agents: agents.length,
  active: agents.filter((agent) => agent.status === "active" || agent.status === "degraded").length,
  instances: agents.reduce((total, agent) => total + agent.instances, 0),
  runs24h: agents.reduce((total, agent) => total + agent.runs24h, 0),
  cost24h: agents.reduce((total, agent) => total + agent.cost24h, 0),
  approvals24h: agents.reduce((total, agent) => total + agent.approvals24h, 0),
  successRate:
    agents.reduce((total, agent) => total + agent.successRate * agent.runs24h, 0) /
    Math.max(
      1,
      agents.reduce((total, agent) => total + agent.runs24h, 0),
    ),
};
